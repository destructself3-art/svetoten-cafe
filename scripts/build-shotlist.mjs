// Builds the photo shot list from docs/shot-list.json:
//   docs/PHOTO_PROMPTS.md   - plain reference for the repo
//   docs/shot-list.html     - standalone page (open locally in a browser)
//   <artifactOut>           - same page as a body fragment for Artifact publishing (optional 2nd arg)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const data = JSON.parse(readFileSync(join(root, "docs/shot-list.json"), "utf8"));

export function composePrompt(shot, d = data) {
  const mode = d.modes[shot.mode];
  return [
    shot.subject,
    shot.light ?? mode.light,
    mode.palette,
    d.style,
    d.negative[shot.people ?? "none"],
    `Aspect ratio ${shot.ratio}.`,
  ].join(" ");
}

const shots = data.shots.map((s) => ({ ...s, prompt: composePrompt(s) }));
const order = { A: 0, B: 1, C: 2 };

// ---------- Markdown ----------
const md = [];
md.push(`# Svetoten — photo shot list`, "");
md.push(`${shots.length} shots. Save every image with the exact file name below (any of jpg/png/webp) into \`${data.dropFolder}\`.`, "");
md.push(`Priorities: ${Object.entries(data.priorities).map(([k, v]) => `**${k}** ${v}`).join(" · ")}`, "");
md.push("## Workflow", "");
md.push("1. Use one model and the same settings for the whole series.");
md.push("2. Generate `hero-day` and `interior-day` first; use them as style references where the tool allows.");
md.push("3. Night pairs (`editFrom`): generate by editing the day image with the Edit prompt, so the framing matches. Use the standalone prompt only if the tool cannot edit.");
md.push("4. Reject images with text, logos or faces. Hands are fine.");
md.push("5. Highest available resolution, at least 2048 px on the long side.", "");
for (const section of data.sections) {
  const list = shots.filter((s) => s.section === section.id).sort((a, b) => order[a.priority] - order[b.priority]);
  if (!list.length) continue;
  md.push(`## ${section.id}`, "");
  for (const s of list) {
    md.push(`### ${s.id}.jpg — ${s.ratio} · priority ${s.priority} · ${s.mode}`, "");
    if (s.edit) {
      md.push(`Edit prompt (attach \`${s.editFrom}\`):`, "", "```text", s.edit, "```", "");
      md.push("Standalone prompt:", "");
    }
    md.push("```text", s.prompt, "```", "");
  }
}
writeFileSync(join(root, "docs/PHOTO_PROMPTS.md"), md.join("\n"), "utf8");

// ---------- HTML ----------
const template = readFileSync(join(root, "scripts/shot-list.template.html"), "utf8");
const payload = JSON.stringify({ ...data, shots }).replace(/</g, "\\u003c");
const fragment = template.replace("/*__DATA__*/null", payload);
const standalone = `<!doctype html>\n<html lang="ru">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n</head>\n<body>\n${fragment}\n</body>\n</html>\n`;
writeFileSync(join(root, "docs/shot-list.html"), standalone, "utf8");

// ---------- Compact metadata for the site (placeholder tone and crop ratio per shot) ----------
const meta = Object.fromEntries(shots.map((s) => [s.id, { mode: s.mode, ratio: s.ratio }]));
writeFileSync(
  join(root, "src/data/shot-meta.ts"),
  `// Generated by scripts/build-shotlist.mjs from docs/shot-list.json. Do not edit by hand.
export const SHOT_META: Record<string, { mode: "day" | "night"; ratio: string }> = ${JSON.stringify(meta, null, 2)};
`,
  "utf8",
);

const artifactOut = process.argv[2];
if (artifactOut) writeFileSync(artifactOut, fragment, "utf8");

const count = (p) => shots.filter((s) => s.priority === p).length;
console.log(`shots: ${shots.length} (A ${count("A")}, B ${count("B")}, C ${count("C")})`);
console.log(`longest prompt: ${Math.max(...shots.map((s) => s.prompt.length))} chars`);
